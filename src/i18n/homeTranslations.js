function mergeRecord(base = {}, copy = {}) {
  return Object.fromEntries(
    Object.entries(base).map(([key, value]) => [
      key,
      typeof value === 'object' && value !== null && !Array.isArray(value) && typeof value !== 'function'
        ? { ...value, ...(copy[key] || {}) }
        : copy[key] || value,
    ]),
  )
}

