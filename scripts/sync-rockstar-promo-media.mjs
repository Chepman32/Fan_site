import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const ROCKSTAR_ORIGIN = 'https://www.rockstargames.com'
const ARTWORK_URL = `${ROCKSTAR_ORIGIN}/VI/media/artwork-wallpapers`
const SCREENSHOTS_URL = `${ROCKSTAR_ORIGIN}/VI/media/screenshots`
const OUTPUT_FILE = resolve('src/data/rockstarPromoMedia.js')

const SOURCE_URLS = {
  artwork: ARTWORK_URL,
  screenshots: SCREENSHOTS_URL,
  ultimate: `${SCREENSHOTS_URL}#ultimate-edition`,
}

const ITEM_PATTERN = /title\\":\\"(.*?)\\",\\"thumbnail\\":\{\\"src\\":\\"(.*?)\\",\\"width\\":(\d+),\\"height\\":(\d+)/g

function decodeRscText(value) {
  return JSON.parse(`"${value}"`)
}

function sectionSlice(html, startMarker, endMarker) {
  const start = html.indexOf(startMarker)

  if (start === -1) {
    throw new Error(`Rockstar media section marker was not found: ${startMarker}`)
  }

  if (!endMarker) return html.slice(start)

  const end = html.indexOf(endMarker, start + startMarker.length)
  if (end === -1) {
    throw new Error(`Rockstar media section boundary was not found: ${endMarker}`)
  }

  return html.slice(start, end)
}

function slugify(value) {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function parseItems(section, collection) {
  const items = []
  const seen = new Set()

  for (const match of section.matchAll(ITEM_PATTERN)) {
    const title = decodeRscText(match[1])
    const path = decodeRscText(match[2])
    const key = `${title}:${path}`

    if (seen.has(key)) continue
    seen.add(key)

    items.push({
      id: `${collection}-${slugify(title)}`,
      title,
      src: new URL(path, ROCKSTAR_ORIGIN).href,
      width: Number(match[3]),
      height: Number(match[4]),
    })
  }

  if (!items.length) {
    throw new Error(`No media items were parsed for ${collection}`)
  }

  return items
}

async function fetchPage(url) {
  const response = await fetch(url, {
    headers: {
      'user-agent': 'LeonidaLootMediaSync/1.0 (+https://leonidaloot.com)',
    },
  })

  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`)
  }

  return response.text()
}

function serialize(data) {
  return `// Generated by scripts/sync-rockstar-promo-media.mjs. Do not edit manually.\n\nexport const rockstarPromoMedia = ${JSON.stringify(data, null, 2)}\n`
}

async function main() {
  const [artworkHtml, screenshotsHtml] = await Promise.all([
    fetchPage(ARTWORK_URL),
    fetchPage(SCREENSHOTS_URL),
  ])

  const artworkSection = sectionSlice(artworkHtml, 'data-track\\":\\"artwork\\"')
  const screenshotsSection = sectionSlice(
    screenshotsHtml,
    'data-track\\":\\"screenshots\\"',
    'id\\":\\"ultimate-edition\\"',
  )
  const ultimateSection = sectionSlice(
    screenshotsHtml,
    'id\\":\\"ultimate-edition\\"',
    'id\\":\\"vintage-vice-city\\"',
  )

  const collections = {
    artwork: parseItems(artworkSection, 'artwork'),
    screenshots: parseItems(screenshotsSection, 'screenshots'),
    ultimate: parseItems(ultimateSection, 'ultimate'),
  }

  const output = {
    syncedAt: new Date().toISOString(),
    sources: SOURCE_URLS,
    collections,
  }

  await writeFile(OUTPUT_FILE, serialize(output), 'utf8')

  const summary = Object.entries(collections)
    .map(([name, items]) => `${name}: ${items.length}`)
    .join(', ')

  console.log(`Synced Rockstar promo media (${summary}) to ${OUTPUT_FILE}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
